# Fetch steward-gateway's GraphQL SDL at the commit pinned in schema-refs.env, assemble it into
# src/product/schema.graphql the same way steward-web does, and record its SHA-256 in
# schema-refs.env. The fetch is the only network step; the tests check the copy offline.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

# shellcheck source=/dev/null
source schema-refs.env

if [[ ! "${STEWARD_GATEWAY_REF}" =~ ^[0-9a-f]{40}$ ]]; then
  echo "schema-copy: STEWARD_GATEWAY_REF must be a full 40-character commit sha." >&2
  exit 1
fi

repo="${STEWARD_GATEWAY_REPO:-https://github.com/Steward-GRC/steward-gateway.git}"
work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

echo "schema-copy: fetching steward-gateway graphql/ at ${STEWARD_GATEWAY_REF}."
git -C "${work}" init -q
git -C "${work}" fetch -q --depth 1 "${repo}" "${STEWARD_GATEWAY_REF}"

# schema.graphqls declares the root types the other files extend, so it goes first.
files=()
while IFS= read -r f; do files+=("${f}"); done < <(
  git -C "${work}" ls-tree --name-only FETCH_HEAD graphql/ | grep '\.graphqls$' | LC_ALL=C sort
)
if [ "${#files[@]}" -eq 0 ]; then
  echo "schema-copy: no graphql/*.graphqls at ${STEWARD_GATEWAY_REF}." >&2
  exit 1
fi
ordered=()
for f in "${files[@]}"; do [ "${f}" = "graphql/schema.graphqls" ] && ordered+=("${f}"); done
for f in "${files[@]}"; do [ "${f}" != "graphql/schema.graphqls" ] && ordered+=("${f}"); done

out="src/product/schema.graphql"
{
  echo "# Generated by scripts/schema-copy.sh. Do not edit."
  echo "# Source: steward-gateway graphql/*.graphqls"
  echo "# steward-gateway commit: ${STEWARD_GATEWAY_REF}"
  for f in "${ordered[@]}"; do
    echo
    echo "# ---- ${f}"
    git -C "${work}" show "FETCH_HEAD:${f}"
  done
} >"${out}"

if command -v sha256sum >/dev/null 2>&1; then
  sum="$(sha256sum "${out}" | cut -d' ' -f1)"
else
  sum="$(shasum -a 256 "${out}" | cut -d' ' -f1)"
fi
tmp="$(mktemp)"
sed -E "s/^STEWARD_GATEWAY_SCHEMA_SHA256=.*/STEWARD_GATEWAY_SCHEMA_SHA256=${sum}/" schema-refs.env >"${tmp}"
mv "${tmp}" schema-refs.env
echo "schema-copy: wrote ${out} (${#ordered[@]} files, sha256 ${sum})."
